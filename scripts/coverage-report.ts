// Generates docs/NARRATIVE_COVERAGE.md from the real content + simulations.
// Run: npm run coverage:story
import { writeFileSync } from 'node:fs';
import { CHAPTERS } from '../src/content/chapters';
import { SIDES } from '../src/content/sides';
import { ALL_ENDINGS, FAMILIES, MOURADS, PATHS, endingFitness, evaluateEnding } from '../src/content/endings';
import { chapterStats, computeReachability } from '../src/game/story/coverage';
import { searchEnding } from '../src/game/story/search';
import { collectSetFlags, validateChapters } from '../src/game/story/validate';
import { GOOD, byTone, phased, playthrough } from '../src/game/story/simulate';
import { spotById } from '../src/game/world/layout';
import { characterById } from '../src/content/characters';

const t0 = Date.now();
const issues = validateChapters(CHAPTERS, SIDES.map((s) => s.dialogue));
const stats = chapterStats(CHAPTERS);
const flags = collectSetFlags(CHAPTERS, SIDES.map((s) => s.dialogue));
const reach = computeReachability(CHAPTERS, 1500, 3000);
for (const id of [...reach.unreached]) {
  for (const seed of [3, 17, 99, 123]) {
    const r = searchEnding(CHAPTERS, evaluateEnding, id, endingFitness(id), { seed, budget: 8000, restarts: 8 });
    if (r.found) {
      reach.reached.set(id, { via: 'search', sample: r.state });
      break;
    }
  }
}
const unreached = ALL_ENDINGS.filter((e) => !reach.reached.has(e.id)).map((e) => e.id);

const journeys: [string, ReturnType<typeof playthrough>][] = [
  ['1. أمين المسؤول (Responsible)', playthrough(CHAPTERS, byTone(GOOD), evaluateEnding)],
  ['2. يهرب ويكذب (Skips & lies)', playthrough(CHAPTERS, byTone(['lie', 'bad', 'neutral', 'good']), evaluateEnding, { late: () => true })],
  ['3. يرفض الضغط (Refuses pressure)', playthrough(CHAPTERS, byTone(['refuse', 'honest', 'help', 'good', 'neutral']), evaluateEnding)],
  ['4. يطيح ويطلب العاون (Mistakes → help)', playthrough(CHAPTERS, phased(byTone(['bad', 'lie', 'neutral']), 31, byTone(['honest', 'help', 'good', 'refuse', 'neutral'])), evaluateEnding)],
  ['5. يرمّم الثقة (Rebuilds trust)', playthrough(CHAPTERS, phased(byTone(['lie', 'bad', 'neutral']), 42, byTone(['honest', 'good', 'help', 'refuse', 'neutral'])), evaluateEnding)],
];

const sum = (k: keyof (typeof stats)[number]) => stats.reduce((a, s) => a + (s[k] as number), 0);
const L: string[] = [];
L.push('# Narrative Coverage Report', '');
L.push(`_Generated by \`npm run coverage:story\` on ${new Date().toISOString().slice(0, 10)} (${((Date.now() - t0) / 1000).toFixed(0)} s)._`, '');
L.push('## Summary', '');
L.push('| Metric | Value |', '|---|---|');
L.push(`| Chapters in registry | ${CHAPTERS.length} / 68 |`);
L.push(`| Objectives (of which conditional / branch-specific) | ${sum('objectives')} (${sum('conditionalObjectives')}) |`);
L.push(`| Dialogue lines | ${sum('lines')} |`);
L.push(`| Player decisions / options | ${sum('decisions')} / ${sum('options')} |`);
L.push(`| Story flags (persistent consequences) | ${flags.size} |`);
L.push(`| Side activities | ${SIDES.length} |`);
L.push(`| Static validation issues | ${issues.length} |`);
L.push(`| Distinct endings defined | ${ALL_ENDINGS.length} |`);
L.push(`| Endings proven reachable | **${reach.reached.size} / ${ALL_ENDINGS.length}** |`);
L.push(`| Simulated playthroughs used | ${reach.runs} |`, '');

L.push('## What counts as a distinct ending', '');
L.push('An ending is the combination of three outcomes that are earned independently over the 68 chapters:', '');
L.push(`- **Path (${PATHS.length})**: ${PATHS.map((p) => `${p.title} (\`${p.id}\`)`).join('، ')}`);
L.push(`- **Family (${FAMILIES.length})**: ${FAMILIES.map((p) => `${p.title} (\`${p.id}\`)`).join('، ')}`);
L.push(`- **Mourad (${MOURADS.length})**: ${MOURADS.map((p) => `${p.title} (\`${p.id}\`)`).join('، ')}`, '');
L.push('Each combination gets its own title and a four-part epilogue (path text, family text, Mourad text, and a path×family closing scene), and the final chapter plays different scenes per outcome. Two endings are only counted as distinct if at least one of the three outcomes differs; 68 chapters do **not** imply 68 endings.', '');
L.push('Reachability is proven by actually playing the game headlessly through the real engine and content: first a population of random/weighted/phased strategies, then a guided evolutionary search for any ending not yet found. Every listed ending below has a concrete playthrough that ends there.', '');

L.push('## Endings', '');
L.push('| # | Ending id | Title | Reached via |', '|---|---|---|---|');
ALL_ENDINGS.forEach((e, i) => {
  const r = reach.reached.get(e.id);
  L.push(`| ${i + 1} | \`${e.id}\` | ${e.title} | ${r ? (r.via === 'random' ? 'random play' : 'guided search') : '**NOT REACHED**'} |`);
});
L.push('');
if (unreached.length) L.push(`**Unreached:** ${unreached.join(', ')}`, '');

L.push('## Contrasting journeys (automated)', '');
L.push('| Journey | Ending | Trust | Honesty | Grades | Attendance | Risk | Mourad |', '|---|---|---|---|---|---|---|---|');
for (const [name, s] of journeys) {
  L.push(`| ${name} | \`${s.ending}\` | ${s.stats.trust} | ${s.stats.honesty} | ${s.stats.grades} | ${s.stats.attendance} | ${s.stats.risk} | ${s.stats.mourad} |`);
}
L.push('');

L.push('## Chapters', '');
L.push('| # | Title | Age | Objectives (cond.) | Lines | Decisions / options | Locations | Characters |', '|---|---|---|---|---|---|---|---|');
for (const s of stats) {
  const locs = s.locations.map((l) => spotById.get(l)?.name ?? l).join('، ');
  const npcs = s.npcs.map((n) => characterById.get(n)?.name ?? n).join('، ');
  L.push(`| ${s.id} | ${s.title} | ${s.age} | ${s.objectives} (${s.conditionalObjectives}) | ${s.lines} | ${s.decisions} / ${s.options} | ${locs} | ${npcs} |`);
}
L.push('');
L.push('## Validation', '');
L.push(issues.length ? issues.map((i) => `- ch${i.chapter} ${i.where}: ${i.message}`).join('\n') : 'No issues: every chapter has an opening and closing scene, ≥3 objectives, ≥1 decision; every objective target exists and is present; every condition parses and references a flag that some content sets; every decision has an unconditional fallback option (no softlocks).');
writeFileSync('docs/NARRATIVE_COVERAGE.md', L.join('\n') + '\n');
console.log(`reached ${reach.reached.size}/${ALL_ENDINGS.length}, issues ${issues.length}, written docs/NARRATIVE_COVERAGE.md`);
